<?php

/**
 * Prints TypeScript interfaces for every APIv4 entity of the running site.
 * Each interface is a full `get` row; `select` narrows it with Pick<>.
 *
 * Run inside the dev stack as a user with full API access (npm run types in frontend/).
 * The output depends on the site's custom fields; regenerate after schema changes.
 */

declare(strict_types = 1);

$tsType = static function (array $field): string {
  $base = match ($field['data_type'] ?? 'String') {
    'Integer', 'Float', 'Money', 'Number' => 'number',
    'Boolean' => 'boolean',
    'Array' => 'unknown[]',
    'Object' => 'Record<string, unknown>',
    default => 'string',
  };
  return $field['serialize'] ? "{$base}[]" : $base;
};
$key = static fn (string $name): string => preg_match('/^[A-Za-z_$][\w$]*$/', $name)
  ? $name
  : var_export($name, return: TRUE);

$out = ['// Generated by scripts/gen-types.php from CiviCRM ' . CRM_Utils_System::version() . '. Do not edit.', ''];
$names = [];
foreach (civicrm_api4('Entity', 'get', ['select' => ['name'], 'orderBy' => ['name' => 'ASC']]) as $entity) {
  try {
    $fields = civicrm_api4($entity['name'], 'getFields', [
      'select' => ['name', 'data_type', 'serialize', 'required', 'options', 'suffixes'],
    ]);
  }
  catch (\Throwable $e) {
    fwrite(STDERR, "skip {$entity['name']}: {$e->getMessage()}\n");
    continue;
  }
  $names[] = $entity['name'];
  $out[] = "export interface {$entity['name']} {";
  foreach ($fields as $field) {
    $type = $tsType($field);
    $nullable = empty($field['required']) ? ' | null' : '';
    $out[] = "  {$key($field['name'])}: {$type}{$nullable};";
    foreach ($field['options'] ? $field['suffixes'] ?? ['name', 'label'] : [] as $suffix) {
      $out[] =
        "  {$key($field['name'] . ':' . $suffix)}: " . ($field['serialize'] ? 'string[]' : 'string') . ' | null;';
    }
  }
  $out[] = '}';
  $out[] = '';
}
$out[] = 'export interface Entities {';
foreach ($names as $name) {
  $out[] = "  {$name}: {$name};";
}
$out[] = '}';
echo implode("\n", $out), "\n";
