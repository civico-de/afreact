<?php

declare(strict_types = 1);

namespace Civi\Afreact;

use Civi\Test\CiviEnvBuilder;
use Civi\Test\HeadlessInterface;
use Civi\Test\TransactionalInterface;
use PHPUnit\Framework\TestCase;

require_once __DIR__ . '/CoreShape.php';
require_once __DIR__ . '/CoreSamples.php';
require_once __DIR__ . '/TypeScriptShape.php';

/**
 * What core sends the renderer, as types (src/api/core.gen.ts). A difference means core changed
 * it; regenerate with `bun run core-shape`, then src/api/coreShape.ts names what the renderer's
 * types lack.
 *
 * @group headless
 */
class CoreShapeHeadlessTest extends TestCase implements HeadlessInterface, TransactionalInterface {

  private const FILE = __DIR__ . '/../../../../src/api/core.gen.ts';

  /**
   * Every component, so that the forms placed for CiviCase and CiviCampaign find their displays;
   * the demo fixture for display settings core's own forms leave out. Menu as in
   * GetFormHeadlessTest::builder().
   */
  public function setUpHeadless(): CiviEnvBuilder {
    return ck_headless()
      ->install(['civi_case', 'civi_campaign', 'org.civicrm.afform_admin', 'civicrm_admin_ui', 'afreactdemo'])
      ->callback(static fn () => \Civi::router()->clear()->rebuild(), 'afreact-menu')
      ->apply();
  }

  public function testGeneratedTypesMatchWhatCoreSends(): void {
    $samples = new CoreSamples();
    $this->assertSame([], $samples->failed(), 'Forms or displays that did not load');

    $generated = TypeScriptShape::file(
      // No core version: the compat matrix runs this against several releases sending one shape.
      '// Generated by tests/phpunit/Civi/Afreact/CoreShapeHeadlessTest.php (bun run core-shape). Do not edit.',
      $samples->shape(),
    );
    if (getenv('AFREACT_WRITE_CORE_SHAPE') === '1') {
      file_put_contents(self::FILE, $generated);
    }
    $this->assertSame(
      (string) file_get_contents(self::FILE),
      $generated,
      'Core changed what it sends; run bun run core-shape',
    );
  }

}
